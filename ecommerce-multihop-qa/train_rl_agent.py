"""
training_rl_agent.py

Main training script for the Adaptive Multi-hop Retrieval RL Agent.

Two-stage training pipeline
----------------------------
STAGE 1 — Imitation Learning
    Warm-up the policy using high-quality heuristic trajectories.
    These trajectories are generated by a simple BFS-ranked retriever
    that selects the top-scoring neighbour at each hop (teacher).

STAGE 2 — Reinforcement Learning (PPO)
    Fine-tune the policy via PPO with the multi-objective reward function.
    LLM judge provides weak supervision reward signal.

Usage
-----
    python training_rl_agent.py --stage both --iterations 100
    python training_rl_agent.py --stage rl   --iterations 200 --resume
"""

